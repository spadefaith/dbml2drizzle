const test = require("node:test");
const assert = require("node:assert/strict");
const { generate, sqlFor } = require("./helpers");

const dbml = `Table users {
  id int [pk, increment]
  email varchar(255) [not null]
  created_at timestamptz [default: \`now()\`]
  indexes {
    email [unique]
  }
}

Table orders {
  id bigint [pk, increment]
  user_id int [ref: > users.id, delete: set null]
  status enum('new','paid') [default: 'new']
}

Table lines {
  order_id bigint
  line_no int
  indexes {
    (order_id, line_no) [pk]
  }
}

Table line_notes {
  order_id bigint
  line_no int
  body text
}

Ref: line_notes.(order_id, line_no) > lines.(order_id, line_no) [delete: cascade]
`;

test("drizzle-kit turns the generated schema into the expected SQL", async () => {
  const sql = await sqlFor(generate(dbml));

  assert.match(sql, /CREATE TYPE "public"\."enum_orders_status" AS ENUM\('new', 'paid'\)/);

  for (const table of ["users", "orders", "lines", "line_notes"]) {
    assert.match(sql, new RegExp(`CREATE TABLE "${table}"`));
  }

  assert.match(sql, /"id" integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY/);
  assert.match(sql, /"created_at" timestamp with time zone DEFAULT now\(\)/);
  assert.match(sql, /"status" "enum_orders_status" DEFAULT 'new'/);
  assert.match(sql, /FOREIGN KEY \("user_id"\) REFERENCES "public"\."users"\("id"\) ON DELETE set null/);
  assert.match(sql, /PRIMARY KEY\("order_id","line_no"\)/);
  assert.match(sql, /FOREIGN KEY \("order_id","line_no"\) REFERENCES "public"\."lines"\("order_id","line_no"\) ON DELETE cascade/);
  assert.match(sql, /CREATE UNIQUE INDEX "users_email" ON "users"/);
});
