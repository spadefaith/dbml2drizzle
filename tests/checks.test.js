const test = require("node:test");
const assert = require("node:assert/strict");
const { parseSchema } = require("../src");
const { generate, sqlFor } = require("./helpers");

const dbml = `Table events {
  id integer [pk]
  starts_at timestamptz [not null]
  ends_at timestamptz [not null]
  seats integer [check: \`seats > 0\`]

  checks {
    \`ends_at > starts_at\` [name: 'events_valid_range']
  }
}
`;

const expected = `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { sql } from "drizzle-orm";
import { check, integer, pgTable, timestamp } from "drizzle-orm/pg-core";

export const events = pgTable("events", {
  id: integer("id").primaryKey(),
  starts_at: timestamp("starts_at", { withTimezone: true }).notNull(),
  ends_at: timestamp("ends_at", { withTimezone: true }).notNull(),
  seats: integer("seats"),
}, (t) => [
  check("events_seats_check", sql\`seats > 0\`),
  check("events_valid_range", sql\`ends_at > starts_at\`),
]);
`;

/**
 * Messages of the DbmlError thrown for `text`, as "<line> <table>.<column>: <message>" (table and column when known).
 */
function errorsOf(text) {
  try {
    parseSchema(text);
  } catch (error) {
    return error.errors.map(({ line, table, column, message }) => `${line}${table ? ` ${table}` : ""}${column ? `.${column}` : ""}: ${message}`);
  }
  assert.fail("expected a DbmlError");
}

test("a table without checks generates as before", () => {
  const output = generate(`Table products {
  id integer [pk]
  price numeric(10, 2) [not null]
}
`);

  assert.equal(
    output,
    `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { integer, numeric, pgTable } from "drizzle-orm/pg-core";

export const products = pgTable("products", {
  id: integer("id").primaryKey(),
  price: numeric("price", { precision: 10, scale: 2 }).notNull(),
});
`,
  );
});

test("a column check becomes a named table constraint", async () => {
  const output = generate(`Table products {
  id integer [pk]
  price numeric(10, 2) [not null, check: \`price >= 0\`]
}
`);

  assert.match(output, /price: numeric\("price", \{ precision: 10, scale: 2 \}\)\.notNull\(\),/);
  assert.match(output, /check\("products_price_check", sql`price >= 0`\),/);
  assert.match(await sqlFor(output), /CONSTRAINT "products_price_check" CHECK \(price >= 0\)/);
});

test("column check errors name the table, column and line", () => {
  assert.deepEqual(
    errorsOf(`Table products {
  a integer [check: 'a >= 0']
  b integer [check: \`\`]
  c integer [check: \`c > 0\`, check: \`c < 9\`]
}
`),
    [
      "2 products.a: check must be a backtick expression, e.g. check: `price >= 0`",
      "3 products.b: Check expression is empty",
      "4 products.c: A column takes one check; use a table checks { } block for more",
    ],
  );
});

test("expressions are carried over exactly", async () => {
  const output = generate(`Table notes {
  body text [check: \`body <> '' and position('\${x}, [y]: //' in body) = 0 and body <> '\\\`'\`]
}
`);
  const sql = await sqlFor(output);

  assert.ok(sql.includes(`CHECK (body <> '' and position('\${x}, [y]: //' in body) = 0 and body <> '\`')`), sql);
});

test("column and table checks generate the contract output", async () => {
  const output = generate(dbml);
  const sql = await sqlFor(output);

  assert.equal(output, expected);
  assert.match(sql, /CONSTRAINT "events_seats_check" CHECK \(seats > 0\)/);
  assert.match(sql, /CONSTRAINT "events_valid_range" CHECK \(ends_at > starts_at\)/);
});

test("table check errors are reported", () => {
  assert.deepEqual(
    errorsOf(`Table a [check: \`1 = 1\`] {
  x integer [check: \`x > 0\`]

  checks {
    \`x < 10\`
    \`x < 20\` [name: 'a_small', note: 'n']
    'x < 30' [name: 'a_q']
    \`\` [name: 'a_empty']
    \`x < 40\` [name: 'a_x_check']
  }

  checks {
    \`x < 50\` [name: 'a_other']
  }
}

checks {
  \`1 = 1\` [name: 'top']
}
`),
    [
      "1 a: Unknown table setting 'check: `1 = 1`'",
        "5 a: Table checks need a name, e.g. [name: 'orders_total_positive']",
      "6 a: Unknown check setting 'note: 'n''",
      "7 a: Check must be a backtick expression",
      "8 a: Check expression is empty",
      "9 a: Duplicate check name 'a_x_check' (also on line 2)",
      "12 a: Table 'a' has more than one checks block",
      "17: 'checks' must be inside a Table",
    ],
  );
});

test("the same DBML always generates the same checks", () => {
  assert.equal(generate(dbml), generate(dbml));
});
