/**
 * Generated Cloudflare D1 schema for `dbml`.
 */
const d1 = (dbml) => generateSchema(dbml, { dialect: "d1", sourceName: "test.dbml" });

const header = "// Generated by dbml2drizzle from test.dbml. Do not edit by hand.\n";

/**
 * Where the relations exports of generated source start.
 */
const relationsStart = (text) => text.search(/\nexport const \w+Relations = /) + 1;

/**
 * Generated source up to its relations exports (ending with one newline).
 */
const beforeRelations = (text) => text.slice(0, relationsStart(text) - 1);

/**
 * The relations exports of generated source.
 */
const relationsOf = (text) => text.slice(relationsStart(text));

// specs/008-cloudflare-d1-dialect/contracts/d1-output.md
const contract = `Table accounts [note: 'People'] {
  id integer [pk, increment]
  email varchar(255) [unique, not null]
  status enum('active', 'closed') [default: 'active']
  balance decimal(10, 2) [default: '0']
  verified boolean [default: false]
  created_at timestamptz [default: \`now()\`]
  prefs jsonb
  manager_id integer [ref: > accounts.id, delete: set null]

  indexes {
    \`lower(email)\` [unique, name: 'accounts_email_ci', where: \`verified = 1\`]
  }
}
`;

const contractTables = `${header}import { relations, sql } from "drizzle-orm";
import { check, integer, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";
import type { AnySQLiteColumn } from "drizzle-orm/sqlite-core";

export const enum_accounts_status = ["active", "closed"] as const;

/** People */
export const accounts = sqliteTable("accounts", {
  id: integer("id").primaryKey({ autoIncrement: true }),
  email: text("email", { length: 255 }).notNull().unique(),
  status: text("status", { enum: enum_accounts_status }).default("active"),
  balance: text("balance").default("0"),
  verified: integer("verified", { mode: "boolean" }).default(false),
  created_at: text("created_at").default(sql\`(CURRENT_TIMESTAMP)\`),
  prefs: text("prefs", { mode: "json" }),
  manager_id: integer("manager_id").references((): AnySQLiteColumn => accounts.id, { onDelete: "set null" }),
}, (t) => [
  uniqueIndex("accounts_email_ci").on(sql\`lower(email)\`).where(sql\`verified = 1\`),
  check("accounts_status_enum", sql\`status IN ('active', 'closed')\`),
]);
`;

test("the contract DBML gives the contract output", () => {
  const output = d1(contract);

  assert.equal(beforeRelations(output), contractTables);
  assert.equal(relationsOf(output), relationsOf(generate(contract)));
});

