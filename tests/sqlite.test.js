test("enum checks quote values and unusual column names, after the declared checks", () => {
  const dbml = `Table a {
  id integer [pk, check: \`id > 0\`]
  "my col" enum('x', "it's")
  plain enum('p')

  checks {
    \`id < 100\` [name: 'a_small']
  }
}
`;

  assert.match(d1(dbml), new RegExp([
    'check\\("a_id_check", sql`id > 0`\\),',
    '  check\\("a_small", sql`id < 100`\\),',
    `  check\\("a_my col_enum", sql\`"my col" IN \\('x', 'it''s'\\)\`\\),`,
    "  check\\(\"a_plain_enum\", sql`plain IN \\('p'\\)`\\),",
  ].join("\n")));
});

const shared = `Table accounts [note: 'People'] {
  id integer [pk]
  email varchar(255) [not null, note: 'Login name']
  created_at timestamp

  indexes {
    email
    (email, created_at) [unique, name: 'accounts_email_created']
    \`lower(email)\` [unique, name: 'accounts_email_ci']
    email [name: 'accounts_email_partial', where: \`created_at is not null\`]
  }
}

Table teams {
  id integer [pk]
  Note {
    'Groups of accounts'
  }
}

Table memberships {
  account_id integer [ref: > accounts.id, delete: cascade]
  team_id integer

  indexes {
    (account_id, team_id) [pk]
  }
}

Table membership_notes {
  account_id integer
  team_id integer
}

Ref: memberships.team_id > teams.id [delete: restrict, update: cascade]
Ref: membership_notes.(account_id, team_id) > memberships.(account_id, team_id) [delete: cascade]
`;

test("references, indexes, composite keys and notes work as for PostgreSQL", () => {
  const output = d1(shared);

  assert.equal(beforeRelations(output), `${header}import { relations, sql } from "drizzle-orm";
import { foreignKey, index, integer, primaryKey, sqliteTable, text, uniqueIndex } from "drizzle-orm/sqlite-core";

/** People */
export const accounts = sqliteTable("accounts", {
  id: integer("id").primaryKey(),
  /** Login name */
  email: text("email", { length: 255 }).notNull(),
  created_at: text("created_at"),
}, (t) => [
  index("accounts_email").on(t.email),
  uniqueIndex("accounts_email_created").on(t.email, t.created_at),
  uniqueIndex("accounts_email_ci").on(sql\`lower(email)\`),
  index("accounts_email_partial").on(t.email).where(sql\`created_at is not null\`),
]);

/** Groups of accounts */
export const teams = sqliteTable("teams", {
  id: integer("id").primaryKey(),
});

export const memberships = sqliteTable("memberships", {
  account_id: integer("account_id").references(() => accounts.id, { onDelete: "cascade" }),
  team_id: integer("team_id").references(() => teams.id, { onDelete: "restrict", onUpdate: "cascade" }),
}, (t) => [
  primaryKey({ columns: [t.account_id, t.team_id] }),
]);

export const membership_notes = sqliteTable("membership_notes", {
  account_id: integer("account_id"),
  team_id: integer("team_id"),
}, (t) => [
  foreignKey({ columns: [t.account_id, t.team_id], foreignColumns: [memberships.account_id, memberships.team_id] }).onDelete("cascade"),
]);
`);
  assert.equal(relationsOf(output), relationsOf(generate(shared)));
});

