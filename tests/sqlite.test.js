test("drizzle-kit turns the contract schema into the expected SQLite SQL", async () => {
  const sql = await sqliteSqlFor(d1(contract));

  assert.match(sql, /CREATE TABLE `accounts`/);
  assert.match(sql, /`id` integer PRIMARY KEY AUTOINCREMENT NOT NULL/);
  assert.match(sql, /`email` text\(255\) NOT NULL/);
  assert.match(sql, /DEFAULT \(CURRENT_TIMESTAMP\)/);
  assert.match(sql, /CONSTRAINT "accounts_status_enum" CHECK\(status IN \('active', 'closed'\)\)/);
  assert.match(sql, /FOREIGN KEY \(`manager_id`\) REFERENCES `accounts`\(`id`\) ON UPDATE no action ON DELETE set null/);
  assert.match(sql, /CREATE UNIQUE INDEX `accounts_email_ci` ON `accounts` \(lower\(email\)\) WHERE verified = 1/);
});

test("drizzle-kit creates every table, key and index of the shared schema", async () => {
  const sql = await sqliteSqlFor(d1(shared));

  for (const table of ["accounts", "teams", "memberships", "membership_notes"]) {
    assert.match(sql, new RegExp(`CREATE TABLE \`${table}\``));
  }

  assert.match(sql, /PRIMARY KEY\(`account_id`, `team_id`\)/);
  assert.match(sql, /FOREIGN KEY \(`account_id`,`team_id`\) REFERENCES `memberships`\(`account_id`,`team_id`\) ON UPDATE no action ON DELETE cascade/);
  assert.match(sql, /CREATE INDEX `accounts_email_partial` ON `accounts` \(`email`\) WHERE created_at is not null/);
  assert.match(sql, /CREATE UNIQUE INDEX `accounts_email_created` ON `accounts` \(`email`,`created_at`\)/);
});

/**
 * Messages of the DbmlError thrown generating `dbml` for D1, as
 * "<line> <table>.<column>: <message>" (table and column when known).
 */
function d1ErrorsOf(dbml) {
  try {
    d1(dbml);
  } catch (error) {
    return error.errors.map(({ line, table, column, message }) => `${line}${table ? ` ${table}` : ""}${column ? `.${column}` : ""}: ${message}`);
  }
  assert.fail("expected a DbmlError");
}

const INCREMENT = "increment on D1 needs the table's single integer primary key";

test("increment outside the single integer primary key is an error", () => {
  const dbml = `Table a {
  id integer [pk]
  n integer [increment]
}

Table b {
  x integer [pk, increment]
  y integer [pk]
}

Table c {
  code varchar(10) [pk, increment]
}

Table d {
  id integer [pk]
  kind enum('x') [increment]
}
`;

  assert.deepEqual(d1ErrorsOf(dbml), [
    `3 a.n: ${INCREMENT}`,
    `7 b.x: ${INCREMENT}`,
    `12 c.code: ${INCREMENT}`,
    `17 d.kind: ${INCREMENT}`,
  ]);
});

test("increment on the single smallint or bigint primary key is allowed", () => {
  const output = d1("Table a {\n  id smallint [pk, increment]\n}\n\nTable b {\n  id bigint [pk, increment]\n}\n");

  assert.match(output, /id: integer\("id"\)\.primaryKey\(\{ autoIncrement: true \}\),/);
  assert.match(output, /id: integer\("id", \{ mode: "number" \}\)\.primaryKey\(\{ autoIncrement: true \}\),/);
});

const indexType = `Table users {
  id integer [pk]
  prefs jsonb

  indexes {
    \`(prefs -> 'tags')\` [type: gin, name: 'users_tags']
  }
}
`;

const checkClash = `Table orders {
  id integer [pk]
  status enum('new', 'paid')

  checks {
    \`id > 0\` [name: 'orders_status_enum']
  }
}
`;

test("an index type is an error on D1, reported at the table", () => {
  assert.deepEqual(d1ErrorsOf(indexType), ["1 users: Index type 'GIN' is not supported on D1"]);
});

test("a declared check named like a generated enum check is an error", () => {
  assert.deepEqual(d1ErrorsOf(checkClash), [
    "3 orders.status: Check name 'orders_status_enum' is declared and also generated for enum column orders.status",
  ]);
});

test("every D1 problem in a DBML is reported in one run", () => {
  assert.deepEqual(d1ErrorsOf(`${indexType}\n${checkClash}`), [
    "1 users: Index type 'GIN' is not supported on D1",
    "12 orders.status: Check name 'orders_status_enum' is declared and also generated for enum column orders.status",
  ]);
});

test("DBML that only D1 rejects still generates for PostgreSQL", () => {
  for (const dbml of [
    indexType,
    checkClash,
    "Table a {\n  id integer [pk]\n  n integer [increment]\n}\n",
    "Table b {\n  x integer [pk, increment]\n  y integer [pk]\n}\n",
  ]) {
    assert.doesNotThrow(() => generate(dbml));
  }
});

test("writeSchema writes nothing when D1 reports an error", () => {
  const { dir, file } = writeTemp("db.dbml", indexType);

  assert.throws(() => writeSchema(file, { dialect: "d1" }), /Index type 'GIN' is not supported on D1/);
  assert.deepEqual(fs.readdirSync(dir), ["db.dbml"]);
});

test("the generated enum check reaches the SQLite SQL, so D1 rejects other values", async () => {
  const sql = await sqliteSqlFor(d1("Table notes {\n  id integer [pk]\n  mood enum('a', \"it's\")\n}\n"));

  assert.match(sql, /CONSTRAINT "notes_mood_enum" CHECK\(mood IN \('a', 'it''s'\)\)/);
});
