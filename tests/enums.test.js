const test = require("node:test");
const assert = require("node:assert/strict");
const { parseSchema } = require("../src");
const { generate, sqlFor } = require("./helpers");

const dbml = `Table orders {
  id integer [pk]
  status order_status [not null, default: 'new']
  kind enum('web', 'shop')
}

Table order_events {
  id integer [pk]
  status order_status
}

Enum order_status {
  Note: 'Lifecycle of an order'
  new
  "in progress" [note: 'being packed']
  shipped
}
`;

const expected = `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { integer, pgEnum, pgTable } from "drizzle-orm/pg-core";

/**
 * Lifecycle of an order
 * in progress: being packed
 */
export const order_status = pgEnum("order_status", ["new", "in progress", "shipped"]);
export const enum_orders_kind = pgEnum("enum_orders_kind", ["web", "shop"]);

export const orders = pgTable("orders", {
  id: integer("id").primaryKey(),
  status: order_status("status").notNull().default("new"),
  kind: enum_orders_kind("kind"),
});

export const order_events = pgTable("order_events", {
  id: integer("id").primaryKey(),
  status: order_status("status"),
});
`;

/**
 * Messages of the DbmlError thrown for `text`, as "<line> <table>.<column>: <message>"
 * (table and column when known).
 */
function errorsOf(text, run = parseSchema) {
  try {
    run(text);
  } catch (error) {
    return error.errors.map(
      ({ line, table, column, message }) => `${line}${table ? ` ${table}` : ""}${column ? `.${column}` : ""}: ${message}`
    );
  }
  assert.fail("expected a DbmlError");
}

test("inline enums generate as before", () => {
  assert.equal(
    generate(`Table orders {
  id integer [pk]
  status enum('new','paid') [default: 'new']
  kind enum('a','b')
}
`),
    `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { integer, pgEnum, pgTable } from "drizzle-orm/pg-core";

export const enum_orders_status = pgEnum("enum_orders_status", ["new", "paid"]);
export const enum_orders_kind = pgEnum("enum_orders_kind", ["a", "b"]);

export const orders = pgTable("orders", {
  id: integer("id").primaryKey(),
  status: enum_orders_status("status").default("new"),
  kind: enum_orders_kind("kind"),
});
`,
  );
});

test("one Enum block is shared by several columns", async () => {
  const output = generate(dbml);
  const sql = await sqlFor(output);

  assert.equal(output, expected);
  assert.equal(sql.match(/CREATE TYPE "public"\."order_status"/g).length, 1);
  assert.ok(sql.includes(`CREATE TYPE "public"."order_status" AS ENUM('new', 'in progress', 'shipped');`), sql);
  assert.equal(sql.match(/"status" "order_status"/g).length, 2);
});

test("unused enums are declared and Note blocks are accepted", () => {
  const text = `Table t {
  id integer
}

Enum unused {
  Note {
    'Not used yet'
  }
  a
  b
}
`;

  assert.match(generate(text), /\/\*\* Not used yet \*\/\nexport const unused = pgEnum\("unused", \["a", "b"\]\);/);
  assert.deepEqual(parseSchema(dbml).enums, [
    {
      name: "order_status",
      values: [{ value: "new" }, { value: "in progress", note: "being packed" }, { value: "shipped" }],
      note: "Lifecycle of an order",
      line: 12,
    },
  ]);
});

test("enum mistakes are reported with their lines", () => {
  assert.deepEqual(
    errorsOf(`Table orders {
  id integer
  status st [default: 'lost']
}

Enum st {
  new
  new
  done [color: 'red']
}

Enum st {
  x
}

Enum empty {
}

Enum text {
  a
}

Enum sales.kind {
  a
}

Enum orders {
  a
}
`),
    [
      "3 orders.status: Default 'lost' is not a value of enum 'st' (new, done)",
      "8: Duplicate value 'new' in enum 'st'",
      "9: Unknown enum value setting 'color: 'red''",
      "12: Duplicate enum 'st' (also on line 6)",
      "16: Enum 'empty' has no values",
      "19: Enum 'text' has the name of a built-in type",
      "23: Schema-qualified enum names are not supported: 'sales.kind'",
      "27: Enum 'orders' has the same name as table 'orders' (line 1)",
    ],
  );
});

test("an enum named like an inline enum's type is reported by the pg dialect", () => {
  assert.deepEqual(
    errorsOf(
      `Table orders {
  kind enum('a', 'b')
}

Enum enum_orders_kind {
  x
}
`,
      generate,
    ),
    ["5: Enum 'enum_orders_kind' has the same name as the enum type of orders.kind (line 2)"],
  );
});

test("names that become the same identifier are reported", () => {
  assert.deepEqual(
    errorsOf(
      `Table t {
  id integer
}

Enum "order-status" {
  a
}

Enum order_status {
  b
}
`,
      generate,
    ),
    ["9: Enum name 'order-status' and 'order_status' both become 'order_status' in generated code"],
  );

  assert.deepEqual(
    errorsOf(
      `Enum "order-items" {
  a
}

Table order_items {
  id integer
}
`,
      generate,
    ),
    ["5 order_items: Table name 'order-items' and 'order_items' both become 'order_items' in generated code"],
  );
});
