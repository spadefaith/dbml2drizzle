// research R3 (revised): backtick expressions may span lines only in a View's as: query
const SPAN_ERROR = "Backtick expressions may span lines only in a View's as: query";

test("a multi-line backtick expression outside a View's as: is an error at its first line", () => {
  assert.deepEqual(errorsOf(`Table t {
  a integer
  checks {
    \`a > 0
    and a < 10\` [name: 'a_range']
  }
}
`), [`4: ${SPAN_ERROR}`]);

  assert.deepEqual(errorsOf(`Table t {
  a integer [check: \`a > 0
    and a < 10\`]
}
`), [`2: ${SPAN_ERROR}`]);

  assert.deepEqual(errorsOf(`Table t {
  a integer
  indexes {
    a [where: \`a > 0
      and a < 10\`]
  }
}
`), [`4: ${SPAN_ERROR}`]);

  assert.deepEqual(errorsOf(`Table t {
  b text
  indexes {
    \`lower(
      b)\` [name: 'b_lower']
  }
}
`), [`4: ${SPAN_ERROR}`]);
});

test("a backtick never closed is reported once, at the line that opened it", () => {
  const errors = errorsOf("Table t {\n  a int [default: `now()]\n}\n");

  assert.equal(errors.filter((error) => error == "2: Backtick expression is missing its closing `").length, 1);
  assert.ok(!errors.some((error) => error.endsWith(SPAN_ERROR)), errors.join("\n"));
});
