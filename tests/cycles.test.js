const test = require("node:test");
const assert = require("node:assert/strict");
const { generateSchema } = require("../src");

const generate = (dbml, dialect = "pg") => generateSchema(dbml, { dialect, sourceName: "test.dbml" });

/**
 * Generated source up to its first relations export.
 */
const tablesOf = (text) => text.slice(0, text.search(/\nexport const \w+Relations = /) + 1);

/**
 * The relations exports of generated source.
 */
const relationsOf = (text) => text.slice(text.search(/\nexport const \w+Relations = /) + 1);

// specs/010-type-correct-self-references/contracts/generated-output.md, "Input"
const dbml = `Table accounts {
  id integer [pk]
  created_by integer [ref: > accounts.id, delete: set null]
}

Table departments {
  id integer [pk]
  manager_id integer [ref: > employees.id]
}

Table employees {
  id integer [pk]
  department_id integer [ref: > departments.id]
  boss_id integer
}

Ref: employees.id < employees.boss_id

Table orders {
  id integer [pk]
  account_id integer [ref: > accounts.id]
}
`;

const tables = (builder, module, type) => `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { relations } from "drizzle-orm";
import { integer, ${builder} } from "${module}";
import type { ${type} } from "${module}";

export const accounts = ${builder}("accounts", {
  id: integer("id").primaryKey(),
  created_by: integer("created_by").references((): ${type} => accounts.id, { onDelete: "set null" }),
});

export const departments = ${builder}("departments", {
  id: integer("id").primaryKey(),
  manager_id: integer("manager_id").references((): ${type} => employees.id),
});

export const employees = ${builder}("employees", {
  id: integer("id").primaryKey(),
  department_id: integer("department_id").references((): ${type} => departments.id),
  boss_id: integer("boss_id").references((): ${type} => employees.id),
});

export const orders = ${builder}("orders", {
  id: integer("id").primaryKey(),
  account_id: integer("account_id").references(() => accounts.id),
});

`;

// the relations exports as generated before feature 010 (unchanged by it)
const relationsBefore = `export const accountsRelations = relations(accounts, ({ one, many }) => ({
  created_by_accounts: one(accounts, { fields: [accounts.created_by], references: [accounts.id], relationName: "accounts_created_by" }),
  accounts_by_created_by: many(accounts, { relationName: "accounts_created_by" }),
  orders: many(orders),
}));

export const departmentsRelations = relations(departments, ({ one, many }) => ({
  manager: one(employees, { fields: [departments.manager_id], references: [employees.id], relationName: "departments_manager_id" }),
  employees_by_department_id: many(employees, { relationName: "employees_department_id" }),
}));

export const employeesRelations = relations(employees, ({ one, many }) => ({
  departments_by_manager_id: many(departments, { relationName: "departments_manager_id" }),
  department: one(departments, { fields: [employees.department_id], references: [departments.id], relationName: "employees_department_id" }),
  boss: one(employees, { fields: [employees.boss_id], references: [employees.id], relationName: "employees_boss_id" }),
  employees_by_boss_id: many(employees, { relationName: "employees_boss_id" }),
}));

export const ordersRelations = relations(orders, ({ one }) => ({
  account: one(accounts, { fields: [orders.account_id], references: [accounts.id] }),
}));
`;

test("references in a cycle get a typed callback (pg)", () => {
  assert.equal(tablesOf(generate(dbml)), tables("pgTable", "drizzle-orm/pg-core", "AnyPgColumn"));
});

test("references in a cycle get a typed callback (d1)", () => {
  assert.equal(tablesOf(generate(dbml, "d1")), tables("sqliteTable", "drizzle-orm/sqlite-core", "AnySQLiteColumn"));
});

test("relations are unchanged", () => {
  assert.equal(relationsOf(generate(dbml)), relationsBefore);
});

test("standalone, reversed and one-to-one self-references are typed", () => {
  const output = generate(`Table accounts {
  id integer [pk]
  partner_id integer [ref: - accounts.id]
  sponsor_id integer
}

Ref: accounts.id < accounts.sponsor_id
`);

  assert.match(output, /partner_id: integer\("partner_id"\)\.unique\(\)\.references\(\(\): AnyPgColumn => accounts\.id\),/);
  assert.match(output, /sponsor_id: integer\("sponsor_id"\)\.references\(\(\): AnyPgColumn => accounts\.id\),/);
});

test("a file with several typed references imports the type once", () => {
  assert.equal(generate(dbml).match(/^import type /gm).length, 1);
});

test("a file without cycles has no typed reference and no type import", () => {
  const output = generate(`Table users {
  id integer [pk]
}

Table orders {
  id integer [pk]
  user_id integer [ref: > users.id]
}
`);

  assert.doesNotMatch(output, /import type |\(\): Any/);
  assert.match(output, /user_id: integer\("user_id"\)\.references\(\(\) => users\.id\),/);
});
