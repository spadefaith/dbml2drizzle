const test = require("node:test");
const assert = require("node:assert/strict");
const { DbmlError } = require("../src");
const { generate } = require("./helpers");

const has = (output, line) => assert.ok(output.includes(line), `missing:\n${line}\n\nin:\n${output}`);

test("starts with the generated header and imports used builders only, sorted", () => {
  const output = generate("Table users {\n  id int [pk]\n  name varchar\n}\n");

  assert.ok(output.startsWith("// Generated by dbml2drizzle from test.dbml. Do not edit by hand.\n"));
  has(output, 'import { integer, pgTable, varchar } from "drizzle-orm/pg-core";');
  assert.ok(output.endsWith("});\n"));
});

test("primary key, not null and unique", () => {
  const output = generate("Table users {\n  id int [pk]\n  email varchar [not null, unique]\n  nick varchar [null]\n}\n");

  has(output, '  id: integer("id").primaryKey(),');
  has(output, '  email: varchar("email").notNull().unique(),');
  has(output, '  nick: varchar("nick"),');
});

test("a composite primary key goes in the extra config", () => {
  const output = generate("Table m {\n  a int\n  b int\n  indexes {\n    (a, b) [pk]\n  }\n}\n");

  has(output, '  a: integer("a"),');
  has(output, "}, (t) => [\n  primaryKey({ columns: [t.a, t.b] }),\n]);");
});

test("indexes: derived and declared names, unique, using", () => {
  const output = generate(`Table posts {
  id int [pk]
  a int
  b int
  indexes {
    (a, b)
    a [unique, name: 'ux']
    b [type: hash]
  }
}
`);

  has(output, '  index("posts_a_b").on(t.a, t.b),');
  has(output, '  uniqueIndex("ux").on(t.a),');
  has(output, '  index("posts_b").using("hash", t.b),');
});

test("inline and standalone references give the same lazy foreign key with actions", () => {
  const users = "Table users {\n  id int [pk]\n}\n";
  const inline = generate(`${users}Table posts {\n  user_id int [ref: > users.id, delete: set null, update: cascade]\n}\n`);
  const standalone = generate(
    `${users}Table posts {\n  user_id int\n}\nRef: posts.user_id > users.id [delete: set null, update: cascade]\n`
  );

  has(inline, '  user_id: integer("user_id").references(() => users.id, { onDelete: "set null", onUpdate: "cascade" }),');
  assert.equal(inline.split("\n").filter((line) => line.includes("references")).join(), standalone.split("\n").filter((line) => line.includes("references")).join());
});

test("references work for self-references and cycles in either order", () => {
  const self = generate("Table users {\n  id int [pk]\n  manager_id int [ref: > users.id]\n}\n");
  has(self, '  manager_id: integer("manager_id").references((): AnyPgColumn => users.id),');

  const a = "Table a {\n  id int [pk]\n  b_id int [ref: > b.id]\n}\n";
  const b = "Table b {\n  id int [pk]\n  a_id int [ref: > a.id]\n}\n";

  for (const output of [generate(a + b), generate(b + a)]) {
    has(output, '  b_id: integer("b_id").references((): AnyPgColumn => b.id),');
    has(output, '  a_id: integer("a_id").references((): AnyPgColumn => a.id),');
  }
});

test("a composite reference becomes foreignKey() with actions", () => {
  const output = generate(`Table b {
  x int
  y int
  indexes {
    (x, y) [pk]
  }
}
Table a {
  x int
  y int
}
Ref: a.(x, y) > b.(x, y) [delete: cascade]
`);

  has(output, '  foreignKey({ columns: [t.x, t.y], foreignColumns: [b.x, b.y] }).onDelete("cascade"),');
});

test("one-to-one makes the foreign key column unique", () => {
  const output = generate("Table users {\n  id int [pk]\n}\nTable profiles {\n  user_id int [ref: - users.id]\n}\n");

  has(output, '  user_id: integer("user_id").unique().references(() => users.id),');
});

test("an enum is declared once before the tables and used by its column", () => {
  const output = generate("Table orders {\n  id int [pk]\n  status enum('a','b') [default: 'a']\n}\n");

  has(output, 'export const enum_orders_status = pgEnum("enum_orders_status", ["a", "b"]);');
  has(output, '  status: enum_orders_status("status").default("a"),');
  assert.ok(output.indexOf("pgEnum(") < output.indexOf("pgTable("));
});

test("notes become JSDoc comments, with */ escaped", () => {
  const output = generate("Table users {\n  id int [pk, note: 'The id */ here']\n  Note: 'People'\n}\n");

  has(output, '/** People */\nexport const users = pgTable("users", {');
  has(output, '  /** The id *\\/ here */\n  id: integer("id").primaryKey(),');
});

test("the same DBML always gives the same output", () => {
  const dbml = `Table users {
  id int [pk, increment]
  status enum('a','b')
}
Table posts {
  id int [pk]
  user_id int [ref: > users.id]
  indexes {
    user_id
  }
}
`;

  assert.equal(generate(dbml), generate(dbml));
});

test("names that are not identifiers are quoted or prefixed, database names kept", () => {
  const output = generate('Table class {\n  "first-name" varchar\n}\n');

  has(output, 'export const _class = pgTable("class", {');
  has(output, '  "first-name": varchar("first-name"),');
});

test("an unknown referenced table is an error naming the column", () => {
  assert.throws(() => generate("Table posts {\n  user_id int [ref: > users.id]\n}\n"), (error) => {
    assert.ok(error instanceof DbmlError);
    assert.match(error.message, /posts\.user_id: References unknown table 'users'/);
    return true;
  });
});

test("renamed_from is an error pointing to drizzle-kit", () => {
  for (const dbml of ["Table a {\n  b int [renamed_from: 'c']\n}\n", "Table a [renamed_from: 'z'] {\n  b int\n}\n"]) {
    assert.throws(() => generate(dbml), /renamed_from is no longer supported: confirm renames in drizzle-kit generate's prompt/);
  }
});
