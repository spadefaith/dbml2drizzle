const test = require("node:test");
const assert = require("node:assert/strict");
const { parseSchema } = require("../src");
const { generate, sqlFor } = require("./helpers");

const dbml = `Table users {
  id integer [pk]
  email varchar(255) [not null]
  created_at timestamptz
  deleted_at timestamptz
  prefs jsonb

  indexes {
    \`lower(email)\` [unique, name: 'users_email_ci']
    (\`lower(email)\`, created_at) [name: 'users_email_created']
    email [unique, where: \`deleted_at is null\`, note: 'active users']
    \`(prefs -> 'tags')\` [type: gin, name: 'users_tags', where: \`prefs is not null\`]
  }
}
`;

const expectedIndexes = `}, (t) => [
  uniqueIndex("users_email_ci").on(sql\`lower(email)\`),
  index("users_email_created").on(sql\`lower(email)\`, t.created_at),
  uniqueIndex("users_email").on(t.email).where(sql\`deleted_at is null\`),
  index("users_tags").using("gin", sql\`(prefs -> 'tags')\`).where(sql\`prefs is not null\`),
]);
`;

/**
 * Messages of the DbmlError thrown for `text`, as "<line> <table>: <message>".
 */
function errorsOf(text) {
  try {
    parseSchema(text);
  } catch (error) {
    return error.errors.map(({ line, table, message }) => `${line}${table ? ` ${table}` : ""}: ${message}`);
  }
  assert.fail("expected a DbmlError");
}

test("plain-column indexes generate as before", () => {
  const output = generate(`Table docs {
  id integer [pk]
  owner_id integer
  kind varchar(20)
  body jsonb

  indexes {
    owner_id [unique]
    (owner_id, kind) [name: 'docs_by_owner']
    body [type: gin]
  }
}
`);

  assert.equal(
    output,
    `// Generated by dbml2drizzle from test.dbml. Do not edit by hand.
import { index, integer, jsonb, pgTable, uniqueIndex, varchar } from "drizzle-orm/pg-core";

export const docs = pgTable("docs", {
  id: integer("id").primaryKey(),
  owner_id: integer("owner_id"),
  kind: varchar("kind", { length: 20 }),
  body: jsonb("body"),
}, (t) => [
  uniqueIndex("docs_owner_id").on(t.owner_id),
  index("docs_by_owner").on(t.owner_id, t.kind),
  index("docs_body").using("gin", t.body),
]);
`,
  );
});

test("expression indexes, alone or mixed with columns", async () => {
  const output = generate(`Table users {
  email varchar(255)
  created_at timestamptz

  indexes {
    \`lower(email)\` [unique, name: 'users_email_ci']
    (\`lower(email)\`, created_at) [name: 'users_email_created']
  }
}
`);
  const sql = await sqlFor(output);

  assert.match(output, /^import \{ sql \} from "drizzle-orm";$/m);
  assert.match(output, /uniqueIndex\("users_email_ci"\)\.on\(sql`lower\(email\)`\),/);
  assert.match(output, /index\("users_email_created"\)\.on\(sql`lower\(email\)`, t\.created_at\),/);
  assert.ok(sql.includes(`CREATE UNIQUE INDEX "users_email_ci" ON "users" USING btree (lower(email));`), sql);
  assert.ok(sql.includes(`CREATE INDEX "users_email_created" ON "users" USING btree (lower(email),"created_at");`), sql);
});

test("expression index errors", () => {
  assert.deepEqual(
    errorsOf(`Table a {
  x varchar
  y integer

  indexes {
    \`lower(x)\`
    \`\` [name: 'a_empty']
    (\`lower(x)\`, y) [pk]
  }
}
`),
    [
      "6 a: Expression indexes need a name, e.g. [name: 'users_email_lower']",
      "7 a: Index expression is empty",
      "8 a: A primary key cannot have an expression or a where condition",
    ],
  );
});

test("expressions and conditions are carried over exactly", async () => {
  const output = generate(`Table notes {
  body text

  indexes {
    \`(position('\${x}, [y]: //' in body) + length('\\\`'))\` [name: 'notes_odd', where: \`body <> '\\\`'\`]
  }
}
`);
  const sql = await sqlFor(output);

  assert.ok(sql.includes(`((position('\${x}, [y]: //' in body) + length('\`'))) WHERE body <> '\`';`), sql);
});

test("partial and expression indexes generate the contract output", async () => {
  const output = generate(dbml);
  const sql = await sqlFor(output);

  assert.ok(output.endsWith(expectedIndexes), output);
  assert.ok(sql.includes(`CREATE UNIQUE INDEX "users_email" ON "users" USING btree ("email") WHERE deleted_at is null;`), sql);
  assert.ok(sql.includes(`USING gin ((prefs -> 'tags')) WHERE prefs is not null;`), sql);
});

test("where condition errors", () => {
  assert.deepEqual(
    errorsOf(`Table a {
  x integer
  y integer

  indexes {
    x [where: 'x > 0']
    y [where: \`\`]
    (x, y) [where: \`x > 0\`, where: \`y > 0\`]
    (y, x) [pk, where: \`x > 0\`]
  }
}
`),
    [
      "6 a: where must be a backtick expression, e.g. where: `deleted_at is null`",
      "7 a: Index condition is empty",
      "8 a: An index takes one where condition",
      "9 a: A primary key cannot have an expression or a where condition",
    ],
  );
});

test("the same DBML always generates the same indexes", () => {
  assert.equal(generate(dbml), generate(dbml));
});
