const contractCopy = `Enum account_status {
  active
  closed
}

Table accounts {
  id integer [pk]
  email varchar(100)
  status account_status [not null]
}

Table active_accounts {
  Note: '''
  View: active_accounts
  select id, email, status
         from accounts
         where status = \\'active\\'

  Accounts that can log in
  '''
  id integer [not null]
  email varchar(100) [note: 'login']
  status account_status
}

Table sales_by_day {
  Note: '''
  Materialized view: sales_by_day
  select created_at::date, sum(amount) from orders group by 1
  '''
  day date [not null]
  total decimal(12, 2)
}
`;

/**
 * The tables @dbml/core reads from a documentation copy, by name.
 */
function standardTables(copy) {
  const { Parser } = require("@dbml/core");
  const database = new Parser().parse(copy, "dbmlv2");
  return new Map(database.schemas[0].tables.map((table) => [table.name, table]));
}

test("US4: each View becomes a Table whose note holds its kind, query and note", () => {
  assert.equal(generateDbPatch(contractDbml), contractCopy);
});

test("US4: the copy parses with @dbml/core and its notes read back the queries exactly", () => {
  const tables = standardTables(generateDbPatch(contractDbml));
  const [active, sales] = parseSchema(contractDbml).views;

  assert.ok(tables.get("active_accounts").note.includes(active.query), tables.get("active_accounts").note);
  assert.ok(tables.get("sales_by_day").note.includes(sales.query), tables.get("sales_by_day").note);

  const quoted = `View q {
  a integer
  as: \`select 'a''b', E'\\\\n', ''''
    from t\`
}
`;
  const query = parseSchema(quoted).views[0].query;
  assert.equal(query, "select 'a''b', E'\\\\n', ''''\n    from t");
  assert.equal(standardTables(generateDbPatch(quoted)).get("q").note, `View: q\n${query}\n`);

  const headed = `View "order view" [materialized] { // reporting
  a integer
  as: \`select 1\`
  Note {
    'Orders by view'
  }
}
`;
  const copy = generateDbPatch(headed);
  assert.ok(copy.startsWith(`Table "order view" { // reporting\n`), copy);
  assert.ok(!copy.includes("Note {"), copy);
  assert.equal(standardTables(copy).get("order view").note, "Materialized view: order view\nselect 1\n\nOrders by view\n");
});

test("US4: the copy keeps the file's \\r\\n line endings", () => {
  const copy = generateDbPatch(contractDbml.replace(/\n/g, "\r\n"));

  assert.ok(!/[^\r]\n/.test(copy), JSON.stringify(copy));
  assert.equal(copy, contractCopy.replace(/\n/g, "\r\n"));
});
