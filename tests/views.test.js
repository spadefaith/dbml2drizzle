test("US1: drizzle-kit creates the view on PostgreSQL and SQLite", async () => {
  const pgSql = await sqlFor(generate(plainDbml));
  assert.ok(pgSql.includes(`CREATE VIEW "public"."active_accounts" AS (select id, email, status
       from accounts
       where status = 'active');`), pgSql);

  const sqlite = generateSchema(plainDbml, { dialect: "sqlite", sourceName: "test.dbml" });
  const view = sqlite.substring(sqlite.indexOf("export const active_accounts"));
  assert.ok(view.startsWith(`export const active_accounts = sqliteView("active_accounts", {`), sqlite);
  assert.ok(view.includes(`  status: text("status", { enum: account_status }),`), view);
  assert.ok(!view.includes("check("), view);

  const sqliteSql = await sqliteSqlFor(sqlite);
  assert.ok(sqliteSql.includes("CREATE VIEW `active_accounts` AS select id, email, status"), sqliteSql);
});

