test("US3: duplicate views and views named like a table or an enum are reported while parsing", () => {
  const dbml = `View v {
  a integer
  as: \`select 1\`
}

View v {
  a integer
  as: \`select 2\`
}

View accounts {
  a integer
  as: \`select 1\`
}

Table accounts {
  id integer [pk]
}

Enum account_status {
  active
}

View account_status {
  a integer
  as: \`select 1\`
}

Table orders {
  id integer [pk]
  view_id integer
}

Ref: orders.view_id > active_accounts.id
`;
  const at = (marker, from) => lineOf(dbml, marker, from);

  assert.deepEqual(errorsOf(dbml), [
    `${at("View v {", 1)} v: Duplicate view 'v' (also on line 1)`,
    `${at("View accounts")} accounts: View 'accounts' has the same name as table 'accounts' (line ${at("Table accounts")})`,
    `${at("View account_status")} account_status: View 'account_status' has the same name as enum 'account_status' (line ${at("Enum account_status")})`,
    `${at("Ref:")} orders.view_id: References unknown table 'active_accounts'`,
  ]);

  // the table declared first
  assert.deepEqual(errorsOf(`Table accounts {
  id integer [pk]
}

View accounts {
  a integer
  as: \`select 1\`
}
`), ["5 accounts: View 'accounts' has the same name as table 'accounts' (line 1)"]);
});

