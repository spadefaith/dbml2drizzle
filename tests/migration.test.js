const test = require("node:test");
const assert = require("node:assert/strict");
const { generateMigration } = require("../src");
const { fakeQueryInterface, loadMigration, FakeSequelize } = require("./helpers");

const shop = `Table orders {
  id integer [pk, increment]
  customer_id integer [ref: > customers.id, delete: cascade, not null]
  status enum('new', 'paid', 'shipped') [default: 'new']
  details jsonb
  placed_at timestamp [default: \`now()\`]

  indexes {
    customer_id
    (customer_id, placed_at) [unique, name: 'orders_by_customer']
    details [type: gin]
  }
}

Table customers {
  id integer [pk, increment]
  referred_by integer [ref: > customers.id, delete: set null]
  email varchar(100) [unique, note: 'login, never shared']

  Note: {
    'People who buy'
  }
}

Table profiles {
  id integer [pk, increment]
  customer_id integer [ref: - customers.id]
}

Table invoices {
  id integer [pk, increment]
  customer_id integer
}

Table customer_links {
  id integer [pk]
  owner_id integer [ref: < invoices.customer_id, delete: cascade]
}

Table order_lines {
  order_id integer
  line_no integer
  qty integer [not null]

  indexes {
    (order_id, line_no) [pk]
  }
}
`;

async function runUp(source) {
  const queryInterface = fakeQueryInterface();
  await loadMigration(source).up(queryInterface, FakeSequelize);
  return queryInterface.calls;
}

const tableOf = (calls, name) =>
  calls.find((call) => call.method == "createTable" && call.args[0] == name);

test("the header names the source DBML file", () => {
  const source = generateMigration(shop, { source: "db.dbml" });
  assert.match(source, /Generated by dbml2sequelize from db\.dbml/);
});

test("tables are created after the tables they reference", async () => {
  const calls = await runUp(generateMigration(shop));
  const created = calls.filter((call) => call.method == "createTable").map((call) => call.args[0]);

  // invoices.customer_id references customer_links (declared with `<`), so customer_links comes first
  assert.deepEqual(created, ["customers", "orders", "profiles", "customer_links", "invoices", "order_lines"]);
});

test("columns carry their types, settings and defaults in contract order", async () => {
  const source = generateMigration(shop);
  const [, columns] = tableOf(await runUp(source), "orders").args;

  assert.deepEqual(Object.keys(columns.id), ["type", "primaryKey", "autoIncrement"]);
  assert.deepEqual(columns.status.type, { type: "ENUM", args: ["new", "paid", "shipped"] });
  assert.equal(columns.status.defaultValue, "new");
  assert.equal(columns.details.type.type, "JSONB");
  assert.deepEqual(columns.placed_at.defaultValue, { fn: "now" });
  assert.match(source, /type: Sequelize\.ENUM\("new", "paid", "shipped"\)/);
  assert.match(source, /defaultValue: Sequelize\.fn\("now"\)/);
});

test("foreign keys land on the right column for >, < and -", async () => {
  const calls = await runUp(generateMigration(shop));

  const orders = tableOf(calls, "orders").args[1];
  assert.deepEqual(orders.customer_id.references, { model: "customers", key: "id" });
  assert.equal(orders.customer_id.onDelete, "CASCADE");
  assert.equal(orders.customer_id.allowNull, false);

  const customers = tableOf(calls, "customers").args[1];
  assert.deepEqual(customers.referred_by.references, { model: "customers", key: "id" });
  assert.equal(customers.referred_by.onDelete, "SET NULL");

  const profiles = tableOf(calls, "profiles").args[1];
  assert.deepEqual(profiles.customer_id.references, { model: "customers", key: "id" });
  assert.equal(profiles.customer_id.unique, true);

  // customer_links.owner_id [ref: < invoices.customer_id] puts the key on invoices.customer_id
  const invoices = tableOf(calls, "invoices").args[1];
  assert.deepEqual(invoices.customer_id.references, { model: "customer_links", key: "owner_id" });
  assert.equal(invoices.customer_id.onDelete, "CASCADE");
  assert.equal(tableOf(calls, "customer_links").args[1].owner_id.references, undefined);
});

test("an index-level pk makes a composite primary key and no index", async () => {
  const calls = await runUp(generateMigration(shop));
  const lines = tableOf(calls, "order_lines").args[1];

  assert.equal(lines.order_id.primaryKey, true);
  assert.equal(lines.line_no.primaryKey, true);
  assert.equal(calls.some((call) => call.method == "addIndex" && call.args[0] == "order_lines"), false);
});

test("table and column comments are kept", async () => {
  const calls = await runUp(generateMigration(shop));
  const customers = tableOf(calls, "customers");

  assert.equal(customers.args[1].email.comment, "login, never shared");
  assert.deepEqual(customers.args[2], { comment: "People who buy", transaction: "tx" });
  assert.deepEqual(tableOf(calls, "orders").args[2], { transaction: "tx" });
});

test("indexes are added with their names, uniqueness and method", async () => {
  const calls = await runUp(generateMigration(shop));
  const indexes = calls.filter((call) => call.method == "addIndex").map((call) => call.args);

  assert.deepEqual(indexes, [
    ["orders", ["customer_id"], { name: "orders_customer_id", transaction: "tx" }],
    ["orders", ["customer_id", "placed_at"], { name: "orders_by_customer", unique: true, transaction: "tx" }],
    ["orders", ["details"], { name: "orders_details", using: "GIN", transaction: "tx" }],
  ]);
});

test("every call in up runs inside the transaction", async () => {
  const calls = await runUp(generateMigration(shop));
  for (const call of calls) {
    assert.equal(call.args[call.args.length - 1].transaction, "tx", `${call.method} ${call.args[0]}`);
  }
});

test("output is deterministic and contains no date", () => {
  const first = generateMigration(shop, { source: "db.dbml" });
  const second = generateMigration(shop, { source: "db.dbml" });

  assert.equal(first, second);
  assert.doesNotMatch(first, /20\d\d-\d\d-\d\d|new Date/);
});
