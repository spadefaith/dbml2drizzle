const parseSchema = require("../parse-schema");
const sortTables = require("./sort-tables");
const {
  str,
  laterConstraints,
  addConstraintSource,
  createTableSource,
  addIndexSource,
  postgresOnly,
  dropEnumSource,
} = require("./sources");

/**
 * Generates the source of a sequelize-cli migration from DBML text
 * (specs/001-dbml-to-migration/contracts/migration-file.md).
 */
module.exports = function generateMigration(dbmlText, { source } = {}) {
  const schema = parseSchema(dbmlText);
  const { ordered, deferred } = sortTables(schema);
  const constraints = laterConstraints(schema.relationships, deferred);

  const inlineRelationship = (table, column) =>
    schema.relationships.find(
      (relationship) =>
        !relationship.composite &&
        relationship.from.table == table &&
        relationship.from.columns[0] == column &&
        !deferred.some((item) => item.table == table && item.column == column)
    );

  const up = [];

  for (const table of ordered) {
    up.push(createTableSource(table, inlineRelationship));
  }

  for (const constraint of constraints) {
    up.push(addConstraintSource(constraint.table, constraint.lines));
  }

  for (const table of ordered) {
    for (const index of table.indexes) {
      up.push(addIndexSource(table.name, index));
    }
  }

  const down = [];

  for (const constraint of [...constraints].reverse()) {
    down.push(
      `      await queryInterface.removeConstraint(${str(constraint.table)}, ${str(constraint.name)}, { transaction });`
    );
  }

  for (const table of [...ordered].reverse()) {
    down.push(`      await queryInterface.dropTable(${str(table.name)}, { transaction });`);
  }

  const enumTypes = ordered.flatMap((table) =>
    table.columns
      .filter((column) => column.type.name == "ENUM")
      .map((column) => `enum_${table.name}_${column.name}`)
  );

  if (enumTypes.length) {
    // Sequelize only drops enum types itself when a model is registered,
    // which never happens inside a migration
    down.push(`\n${postgresOnly(enumTypes.map(dropEnumSource))}`);
  }

  const header = source
    ? `/**\n * Generated by dbml2sequelize from ${source}.\n * Regenerate it from the DBML instead of editing it by hand.\n */\n`
    : "";

  return `"use strict";

${header}/** @type {import('sequelize-cli').Migration} */
module.exports = {
  async up(queryInterface, Sequelize) {
    await queryInterface.sequelize.transaction(async (transaction) => {
${up.join("\n\n")}
    });
  },

  async down(queryInterface, Sequelize) {
    await queryInterface.sequelize.transaction(async (transaction) => {
${down.join("\n")}
    });
  },
};
`;
};
